"""Independent ALL-word binomial rebuild and literal ALL-shift C checker."""
from pathlib import Path
from collections import Counter
from math import comb
import json,time,hashlib
ROOT=Path(__file__).resolve().parent


def main():
    start=time.monotonic();p=json.loads((ROOT/'one_jump_fixed_capacity_C_entrance.json').read_text(encoding='utf8'))
    assert p['status']=='COMPLETE_FIXED_CAPACITY_ONE_JUMP_C_ENTRANCE'
    counts=Counter();rows=[]
    for row in p['rows']:
        L=row['L'];H=L+2;assert row['H']==H
        c=Counter();digest=hashlib.sha256();minC=None;minLC=None
        for h in range(1,H+1):
            N=2*h+L
            P=[sum(comb(j,n-j) for j in range(h) if 0<=n-j<=j) for n in range(N+2)]
            binprefix=[sum(comb(h,j) for j in range(min(h,n)+1)) if n>=0 else 0 for n in range(N+2)]
            def bs(n):return 0 if n<0 else binprefix[min(n,N+1)]
            for alpha in range(1,h+L+1):
                B=[P[n]+bs(n-h)-bs(n-h-alpha-1) for n in range(N+2)]
                F=[1]+[sum(B[max(0,n-L):n]) for n in range(1,N+2)]
                slopes=[0,0]+[max(0,F[n]-F[n-1]) for n in range(2,N+2)]
                R=max(n for n,x in enumerate(slopes) if x)
                assert R<=N and all(slopes[n]>0 for n in range(2,R+1))
                # Rebuild the used actual ordinary prefix by integrating D,
                # then its CDF.  No direct cumulative of producer F is used.
                integrated=[1,1]
                for n in range(2,R+1):integrated.append(integrated[-1]+slopes[n])
                assert integrated==F[:R+1]
                G=[sum(integrated[:k+1]) for k in range(R+1)]
                for n in range(4,R+1):
                    # Every literal shift, not just the producer's ratio envelope.
                    vals=[G[k]*slopes[n-1]-G[k-1]*slopes[n] for k in range(1,n-2)]
                    assert all(v>=0 for v in vals),(L,h,alpha,n)
                    # Reconstruct the exact same strongest ratio only to
                    # compare its reported summary margin, after ALL checks.
                    best=1
                    for k in range(2,n-2):
                        if G[k]*G[best-1]<G[best]*G[k-1]:best=k
                    slack=G[best]*slopes[n-1]-G[best-1]*slopes[n]
                    minC=slack if minC is None else min(minC,slack)
                    c['ALL_current_ranks_envelope_checked']+=1
                    c['ALL_shift_comparisons_covered']+=len(vals)
                if h==H:
                    for n in range(h+2,R+1):
                        minor=slopes[n]**2-slopes[n-1]*slopes[n+1]
                        assert minor>=0,(L,h,alpha,n,minor)
                        c['ALL_full_tail_base_minors']+=1
                        minLC=minor if minLC is None else min(minLC,minor)
                    c['ALL_full_tail_base_padding_classes']+=1
                digest.update((json.dumps([L,h,alpha,R,F],separators=(',',':'))+'\n').encode())
                c['ALL_actual_entrance_words']+=1
        assert c==row['counts'] and digest.hexdigest()==row['all_actual_prefix_sha256'],L
        assert minC==row['minimum_C_envelope_slack'] and minLC==row['minimum_LC_base_minor']
        counts.update(c);rows.append(dict(L=L,H=H,counts=dict(c),all_actual_prefix_sha256=digest.hexdigest()))
        print(json.dumps(dict(L=L,seconds=time.monotonic()-start)),flush=True)
    assert counts==p['counts']
    out=dict(status='PASS_INDEPENDENT_COMPLETE_FIXED_CAPACITY_ONE_JUMP_C_ENTRANCE',
        max_capacity=p['max_capacity'],counts=dict(counts),rows=rows,
        producer_sha256=hashlib.sha256((ROOT/'one_jump_fixed_capacity_C_entrance.json').read_bytes()).hexdigest(),
        seconds=time.monotonic()-start,
        scope='NO producer/arm implementation import. ALL actual prefixes regenerated by explicit binomial closed form plus direct finite sums, exact ALL shift minors literally checked, full LC entrance/minima/hashes match. Universal word coverage/tail induction/C seeds/alpha-clamp separate written/formal assembly. No arbitrary-L/original UI claim.')
    (ROOT/'one_jump_fixed_capacity_C_entrance_verification.json').write_text(json.dumps(out,indent=2)+'\n',encoding='utf8')
    print(json.dumps({k:v for k,v in out.items() if k!='rows'}),flush=True)


if __name__=='__main__':main()
